/**
 * What a job accepts as a file, and how big it may be.
 *
 * One table read from both sides, the same spirit as `BRAND_IMAGES`: the
 * browser checks a file before uploading it, and the upload route checks the
 * same rule before handing out a token — so a hand-crafted request can't get
 * past the second because the first was skipped.
 *
 * The type is decided by the **extension**, not by what the browser reports.
 * Browsers report nothing at all for a `.dwg`, and something different for a
 * `.mov` on each platform; the extension is the one thing every side agrees on,
 * and the content type the file is stored with comes from this table.
 */

const MB = 1024 * 1024;

export type FileKind = "image" | "video" | "pdf" | "document";

export type FileRule = {
  contentType: string;
  kind: FileKind;
  /** The most the stored file may weigh. */
  maxBytes: number;
  /** Re-encoded in the browser before upload: phone photos are 5–12 MB each. */
  compress?: boolean;
};

/** After compression a photo is well under a megabyte; this is the ceiling for one that couldn't be. */
const IMAGE_MAX = 25 * MB;
/** Uploaded as they are — compressing video on a phone isn't viable. */
const VIDEO_MAX = 500 * MB;
/** Plans run large: there are 99 MB drawings in the jobs being moved over. */
const DOCUMENT_MAX = 150 * MB;

export const JOB_FILE_RULES: Record<string, FileRule> = {
  jpg: { contentType: "image/jpeg", kind: "image", maxBytes: IMAGE_MAX, compress: true },
  jpeg: { contentType: "image/jpeg", kind: "image", maxBytes: IMAGE_MAX, compress: true },
  png: { contentType: "image/png", kind: "image", maxBytes: IMAGE_MAX, compress: true },
  webp: { contentType: "image/webp", kind: "image", maxBytes: IMAGE_MAX, compress: true },
  mp4: { contentType: "video/mp4", kind: "video", maxBytes: VIDEO_MAX },
  m4v: { contentType: "video/x-m4v", kind: "video", maxBytes: VIDEO_MAX },
  mov: { contentType: "video/quicktime", kind: "video", maxBytes: VIDEO_MAX },
  webm: { contentType: "video/webm", kind: "video", maxBytes: VIDEO_MAX },
  pdf: { contentType: "application/pdf", kind: "pdf", maxBytes: DOCUMENT_MAX },
  doc: { contentType: "application/msword", kind: "document", maxBytes: DOCUMENT_MAX },
  docx: {
    contentType: "application/vnd.openxmlformats-officedocument.wordprocessingml.document",
    kind: "document",
    maxBytes: DOCUMENT_MAX,
  },
  xls: { contentType: "application/vnd.ms-excel", kind: "document", maxBytes: DOCUMENT_MAX },
  xlsx: {
    contentType: "application/vnd.openxmlformats-officedocument.spreadsheetml.sheet",
    kind: "document",
    maxBytes: DOCUMENT_MAX,
  },
  ppt: { contentType: "application/vnd.ms-powerpoint", kind: "document", maxBytes: DOCUMENT_MAX },
  pptx: {
    contentType: "application/vnd.openxmlformats-officedocument.presentationml.presentation",
    kind: "document",
    maxBytes: DOCUMENT_MAX,
  },
  csv: { contentType: "text/csv", kind: "document", maxBytes: DOCUMENT_MAX },
  txt: { contentType: "text/plain", kind: "document", maxBytes: DOCUMENT_MAX },
  dwg: { contentType: "image/vnd.dwg", kind: "document", maxBytes: DOCUMENT_MAX },
  dxf: { contentType: "image/vnd.dxf", kind: "document", maxBytes: DOCUMENT_MAX },
};

/**
 * What a phone photo may weigh *before* it is compressed. Above this the
 * browser would struggle to decode it at all, and nothing a phone takes is
 * this large.
 */
export const MAX_SOURCE_IMAGE_BYTES = 80 * MB;

/** The long edge a photo is brought down to — still sharp on a large screen. */
export const IMAGE_MAX_EDGE = 2560;
/** The long edge of the gallery copy. */
export const THUMBNAIL_EDGE = 480;
/** A PDF's first page is drawn at this width: wide enough that a cover sheet's title still reads on the tile. */
export const PDF_THUMBNAIL_WIDTH = 720;
/** Thumbnails are generated by us; anything heavier means something went wrong. */
export const THUMBNAIL_MAX_BYTES = 2 * MB;
/** Below this, and within the edge, a photo is already small enough to leave alone. */
const COMPRESS_ABOVE_BYTES = 1.5 * MB;

/** For the file input's `accept`. Lists the image types explicitly, which is what makes iOS hand over a JPEG instead of a HEIC. */
export const JOB_FILE_ACCEPT = Object.keys(JOB_FILE_RULES)
  .map((ext) => `.${ext}`)
  .concat([...new Set(Object.values(JOB_FILE_RULES).map((rule) => rule.contentType))])
  .join(",");

export function extensionOf(name: string): string {
  const dot = name.lastIndexOf(".");
  return dot > 0 ? name.slice(dot + 1).toLowerCase() : "";
}

export function fileRule(name: string): FileRule | null {
  return JOB_FILE_RULES[extensionOf(name)] ?? null;
}

export type FileCheck =
  | { ok: true; rule: FileRule }
  | { ok: false; reason: "empty" | "type" | "heic" | "size" };

/**
 * Checked in the browser before anything is sent. A photo that will be
 * compressed is held to the source ceiling rather than the stored one — what
 * matters for it is what it weighs after.
 */
export function checkJobFile(file: { name: string; size: number }): FileCheck {
  if (!file.name || file.size === 0) return { ok: false, reason: "empty" };
  const ext = extensionOf(file.name);
  // Said apart from "not accepted": an iPhone photo is exactly what this is
  // for, and the person needs to know it's the format, not the photo.
  if (ext === "heic" || ext === "heif") return { ok: false, reason: "heic" };
  const rule = JOB_FILE_RULES[ext];
  if (!rule) return { ok: false, reason: "type" };
  const ceiling = rule.compress ? MAX_SOURCE_IMAGE_BYTES : rule.maxBytes;
  if (file.size > ceiling) return { ok: false, reason: "size" };
  return { ok: true, rule };
}

/** Whether a photo needs re-encoding: too heavy, or larger than any screen will show. */
export function shouldCompress(rule: FileRule, image: { size: number; width: number; height: number }): boolean {
  if (!rule.compress) return false;
  return image.size > COMPRESS_ABOVE_BYTES || Math.max(image.width, image.height) > IMAGE_MAX_EDGE;
}

/**
 * The format a compressed photo is stored in. JPEG stays JPEG; a PNG or WebP
 * becomes WebP, which keeps the transparency of a screenshot or a logo where
 * JPEG would paint it black.
 */
export function compressedType(contentType: string): "image/jpeg" | "image/webp" {
  return contentType === "image/jpeg" ? "image/jpeg" : "image/webp";
}

/** `site photo.png` → `site photo.webp` when the photo changed format on the way. */
export function renameForType(name: string, contentType: string): string {
  const ext = contentType === "image/jpeg" ? "jpg" : contentType === "image/webp" ? "webp" : null;
  if (!ext) return name;
  const current = extensionOf(name);
  if (JOB_FILE_RULES[current]?.contentType === contentType) return name;
  const stem = current ? name.slice(0, -(current.length + 1)) : name;
  return `${stem}.${ext}`;
}

/** Everything a job stores lives under this, which is what the server checks before trusting a path. */
export function jobUploadPrefix(companyId: string, jobId: string): string {
  return `companies/${companyId}/jobs/${jobId}/`;
}

/** The path a file is uploaded to. Blob adds a random suffix, so two `IMG_0001.jpg` never collide. */
export function jobFilePathname(prefix: string, name: string, variant?: "thumbnail"): string {
  const ext = extensionOf(name);
  const stem = (ext ? name.slice(0, -(ext.length + 1)) : name)
    .normalize("NFD")
    .replace(/[̀-ͯ]/g, "")
    .replace(/[^a-zA-Z0-9._-]+/g, "-")
    .replace(/-+/g, "-")
    .replace(/^[-.]+|[-.]+$/g, "")
    .slice(0, 80);
  const base = `${stem || "file"}${ext ? `.${ext}` : ""}`;
  return `${prefix}${variant === "thumbnail" ? "thumbnails/" : ""}${base}`;
}

/** A path under this job's prefix, with no way of climbing out of it. */
export function isUnderPrefix(pathname: string, prefix: string): boolean {
  if (!pathname.startsWith(prefix)) return false;
  const rest = pathname.slice(prefix.length);
  if (!rest) return false;
  return !rest.split("/").some((segment) => segment === "" || segment === "." || segment === "..");
}

export type UploadAllowance = { allowedContentTypes: string[]; maximumSizeInBytes: number };

/**
 * What the upload route hands a token out for: a path under this job, of a
 * type in the table, capped at that type's size. Null refuses the upload.
 */
export function uploadAllowance(pathname: string, prefix: string): UploadAllowance | null {
  if (!isUnderPrefix(pathname, prefix)) return null;
  const rule = fileRule(pathname);
  if (!rule) return null;
  const thumbnail = pathname.slice(prefix.length).startsWith("thumbnails/");
  if (thumbnail) {
    if (rule.kind !== "image") return null;
    return { allowedContentTypes: [rule.contentType], maximumSizeInBytes: THUMBNAIL_MAX_BYTES };
  }
  return { allowedContentTypes: [rule.contentType], maximumSizeInBytes: rule.maxBytes };
}

/**
 * Whether a URL the browser reports back is really the stored file at that
 * path. Without this a registered file could point anywhere on the internet,
 * with a path that passed the prefix check.
 */
export function isBlobUrlFor(url: string, pathname: string): boolean {
  let parsed: URL;
  try {
    parsed = new URL(url);
  } catch {
    return false;
  }
  if (parsed.protocol !== "https:") return false;
  if (!parsed.hostname.endsWith(".blob.vercel-storage.com")) return false;
  try {
    return decodeURIComponent(parsed.pathname) === `/${pathname}`;
  } catch {
    return false;
  }
}

/** The filter on Docs & Files: photos, videos, and everything else read as a document. */
export type FileFilter = "images" | "videos" | "documents";

export function kindOfContentType(contentType: string): FileKind {
  if (contentType.startsWith("image/") && !contentType.startsWith("image/vnd.")) return "image";
  if (contentType.startsWith("video/")) return "video";
  if (contentType === "application/pdf") return "pdf";
  return "document";
}

export function matchesFilter(contentType: string, filter: FileFilter | null): boolean {
  if (!filter) return true;
  const kind = kindOfContentType(contentType);
  if (filter === "images") return kind === "image";
  if (filter === "videos") return kind === "video";
  return kind === "pdf" || kind === "document";
}

export function fileFilterFromParam(value: string | string[] | undefined): FileFilter | null {
  return value === "images" || value === "videos" || value === "documents" ? value : null;
}
